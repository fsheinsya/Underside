
/// <summary>
/// 行動AIの方針を決める性格。ActionAI がこの値に応じて所持スキルの選び方を切り替える。
/// MonsterSpawnRules のモード別候補から抽選し、MonsterFactory が所持スキルを作る。
/// ランキング限定の性格は末尾に追加し、RankingOnlyPersonalities へ登録する。
/// 以下の「固有枠」は通常の70%枠を指す。残り30%では通常攻撃・属性魔法を選ぶ。
/// 例外は大胆（強撃70%・通常攻撃30%）、挑戦・中二（固有技のみ）、無能の覚醒前（通常攻撃のみ）。
/// 並び順を変えると保存済みの数値との対応が変わる。名前の変更も参照元の修正が必要なので別作業として扱う。
/// </summary>

public enum PersonalityType
{
    Bold,       // 0・大胆：ChooseSkillで強撃70%・通常攻撃30%。封印中は通常攻撃。
    Calm,       // 1・冷静：固有枠で1～2ターン目は防御・回復を探し、3ターン目以降はPower最大。防御技がなければ代替攻撃。
    faith,   // 2・信仰：固有枠で相手の直近の技種別を自分の所持技から探し、なければ所持技を等確率抽選。
    Taunt,      // 3・挑発：固有枠で奇数ターンはPower最小、偶数ターンはPower最大。
    Aggressive, // 4・挑戦：成功率の比較はせず、InstantDeathを指定して選ぶ。封印・技なしなら待機。
    Timid,      // 5・臆病：固有枠でHP半分以下なら回復。そうでなければ無敵を探し、なければ所持技を抽選。
    Delusional, // 6・中二：Delusionだけを選ぶ。効果なしの自称必殺技で、封印・技なしなら待機。
    Inept,      // 7・無能：覚醒前は通常攻撃のみ。10ターン目以降に一度だけ能力4倍・全回復し、固有枠でPower最大を選ぶ。
    Stoic,      // 8・克己：固有枠でPower最大。生存してHPが減るたび、基本攻撃・防御・素早さの倍率が0.1ずつ上がる。
    Explorer,   // 9・探求：固有枠で発掘。回復薬・強化薬・爆弾・石ころの抽選はSkillExecutor.ExecuteDig。
    Devoted,    // 10・献身：固有枠で全身全霊。現在HPを追加威力に使い、成功時は自分のHPを1にする。
    Adversity,  // 11・逆境：固有枠でPower最大。属性不利なら攻撃・防御・素早さ1.2倍、成長率100%。
    Unyielding, // 12・不屈：固有枠でPower最大。致死ダメージを初回は必ず、以降は50%でHP1に耐える。
    Impatient,  // 13・短気：固有枠内で35%は我慢の限界、65%は我慢。我慢ごとに専用技のダメージ×1.1、使用後に蓄積を消費。
    Headlong,   // 14・猛進：固有枠で2ターンずつ強撃→絡め手→回復または防御強化を繰り返す。
    Obsessive,  // 15・執念：固有枠でPower最大。毒・封印の翌ターン以降とスタンで休んだ翌ターンは攻撃力2倍。
    Sincere,    // 16・誠実：固有枠でHP半分より多ければ攻撃強化、半分以下ならPower最大。
    Insidious,  // 17・陰湿：固有枠で絡め手。相手が弱った・弱体が揃った・無効と分かったら通常攻撃。
    Adaptive,   // 18・適応：固有枠でHP1/3以下なら再生、それ以外は通常攻撃。耐性蓄積はPersonalityRules。
    Flexible    // 19・柔軟：固有枠で相手の許可された攻撃技をコピー。元のダメージの80%、対象制限と適応相手の50%判定あり。
}


